#!/usr/bin/env python3
"""Night Sentinel - city kit atlas: 256x128 4bpp (8x4 tiles of 32x32), 4 CLUT variants,
plus a 1024-entry sine table (4096 = 1.0). Output: ../city_data.h"""
import math, os, random
import numpy as np

random.seed(7)
W, H = 256, 128
A = np.zeros((H, W), np.uint8)

def tile(i): return (i % 8) * 32, (i // 8) * 32
def rect(i, x0, y0, x1, y1, c):
    ox, oy = tile(i); A[oy+y0:oy+y1+1, ox+x0:ox+x1+1] = c
def fill(i, c): rect(i, 0, 0, 31, 31, c)
def px(i, x, y, c):
    ox, oy = tile(i); A[oy+y, ox+x] = c
def frame(i, x0, y0, x1, y1, c):
    rect(i, x0, y0, x1, y0, c); rect(i, x0, y1, x1, y1, c)
    rect(i, x0, y0, x0, y1, c); rect(i, x1, y0, x1, y1, c)
def specks(i, n, c):
    for _ in range(n): px(i, random.randrange(32), random.randrange(32), c)

# palette semantic: 0 dark,1 wall,2 wall dark,3 wall light,4 glass,5 lit,6 metal,7 door,
# 8 roof,9 asphalt,10 yellow,11 sidewalk,12 curb,13 crate,14 neon red,15 white
fill(0, 9); specks(0, 30, 2); specks(0, 8, 12)                       # 0 asphalt
fill(1, 9); specks(1, 14, 2)
for y in range(3, 20): rect(1, 15, y, 16, y, 10)                       # 1 road dash
fill(2, 11); rect(2, 0, 0, 31, 0, 12); rect(2, 0, 0, 0, 31, 12); specks(2, 12, 3)   # 2 sidewalk
fill(3, 11); rect(3, 26, 0, 31, 31, 12); rect(3, 25, 0, 25, 31, 3); specks(3, 8, 3)  # 3 curb
fill(4, 1)                                                            # 4 wall
for y in (0, 16): rect(4, 0, y, 31, y, 2)
for y in range(0, 32, 16):
    for x in ((0, 16) if y == 0 else (8, 24)): rect(4, x, y, x, y + 15, 2)
rect(4, 0, 1, 31, 1, 3)
def window(i, glass):
    fill(i, 1); rect(i, 0, 0, 31, 0, 2)
    rect(i, 7, 5, 24, 26, 6); rect(i, 8, 6, 23, 25, glass)
    rect(i, 15, 6, 16, 25, 6); rect(i, 8, 15, 23, 16, 6); rect(i, 6, 27, 25, 28, 3)
    if glass == 5: rect(i, 9, 7, 14, 10, 15)
window(5, 4); window(6, 5)                                            # 5 dark / 6 lit window
fill(7, 1); rect(7, 4, 2, 27, 31, 6); rect(7, 6, 4, 25, 31, 7)         # 7 door
rect(7, 9, 7, 22, 15, 4); px(7, 22, 20, 15); px(7, 22, 21, 15)
fill(8, 8); specks(8, 40, 2); specks(8, 12, 12); frame(8, 0, 0, 31, 31, 12)   # 8 roof
fill(9, 1)                                                            # 9 shop front
rect(9, 0, 0, 31, 5, 14)
for x in range(0, 32, 8): rect(9, x, 0, x + 3, 5, 15)
rect(9, 2, 8, 29, 28, 6); rect(9, 3, 9, 28, 27, 5)
rect(9, 15, 9, 16, 27, 6); rect(9, 3, 18, 28, 18, 6)
fill(10, 6); rect(10, 0, 0, 31, 1, 3); rect(10, 0, 30, 31, 31, 2)       # 10 trim
fill(11, 13); frame(11, 0, 0, 31, 31, 2); frame(11, 1, 1, 30, 30, 2)   # 11 crate
for k in range(2, 30): px(11, k, k, 2); px(11, 31 - k, k, 2)
for y in range(32):                                                   # 12 floor
    for x in range(32): px(12, x, y, 11 if ((x // 8) + (y // 8)) % 2 == 0 else 12)
fill(13, 0); frame(13, 1, 1, 30, 30, 15)                               # 13 neon
for (a, b, c_, d) in ((5, 6, 10, 25), (12, 6, 14, 25), (16, 6, 26, 8), (16, 15, 24, 17), (16, 23, 26, 25), (22, 9, 26, 22)):
    rect(13, a, b, c_, d, 14)
fill(14, 3); rect(14, 0, 26, 31, 31, 6); rect(14, 0, 25, 31, 25, 2)      # 14 interior wall (zoccolo)
fill(16, 3); rect(16, 0, 0, 0, 31, 2); specks(16, 10, 1)                  # 16 interior plain
fill(15, 6); rect(15, 3, 3, 28, 17, 0); rect(15, 4, 4, 27, 16, 4)       # 15 console
for y in (6, 9, 12): rect(15, 6, y, 6 + (y * 7) % 17 + 6, y, 5)
for x in (5, 11, 17, 23): rect(15, x, 21, x + 3, 25, 14 if x == 5 else 15)
rect(15, 3, 28, 28, 29, 2)
# 16..: crate-top reused as tile 11.  (rest of the atlas left as 0)

def c15(r, g, b):
    v = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
    return v if v else 0x0421
base = [(8, 8, 14), (70, 70, 84), (50, 50, 62), (96, 96, 112), (20, 28, 52), (240, 200, 90), (110, 116, 130),
        (46, 34, 30), (36, 36, 44), (44, 46, 56), (230, 190, 40), (100, 102, 112), (62, 62, 72), (120, 84, 44),
        (230, 50, 60), (235, 235, 240)]
def variant(over):
    p = list(base)
    for k, v in over.items(): p[k] = v
    return [c15(*c) for c in p]
cluts = [variant({}),
         variant({1: (52, 76, 140), 2: (36, 52, 104), 3: (84, 112, 176), 4: (18, 30, 66), 5: (250, 214, 110), 6: (130, 150, 190), 7: (30, 24, 40)}),
         variant({1: (140, 70, 52), 2: (96, 44, 36), 3: (176, 100, 76), 4: (28, 22, 34), 5: (255, 206, 96), 6: (150, 140, 130), 7: (50, 34, 24), 8: (44, 36, 36)}),
         variant({1: (40, 120, 120), 2: (28, 84, 90), 3: (84, 160, 150), 4: (14, 36, 50), 5: (255, 226, 130), 6: (140, 170, 170), 7: (26, 38, 40), 8: (36, 44, 48)})]

flat = A.reshape(-1)
packed = (flat[0::2] | (flat[1::2] << 4)).astype(np.uint8)
words = packed.view("<u4")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "city_data.h")
with open(out, "w") as f:
    f.write("/* AUTO-GENERATED by tools/gen_city.py - do not edit */\n#ifndef CITY_DATA_H\n#define CITY_DATA_H\n#include <stdint.h>\n\n")
    f.write("/* sine table: 1024 entries per turn, 4096 = 1.0 */\nstatic const int16_t sintab[1024] = {\n")
    for i in range(0, 1024, 16):
        f.write("\t" + ",".join(str(int(round(math.sin(2 * math.pi * k / 1024) * 4096))) for k in range(i, i + 16)) + ",\n")
    f.write("};\n\n/* city atlas 256x128 4bpp = 64x128 halfwords in VRAM; 8x4 tiles of 32x32 */\n")
    f.write("static const uint32_t city_tex[%d] __attribute__((aligned(4))) = {\n" % len(words))
    for i in range(0, len(words), 8):
        f.write("\t" + ",".join("0x%08x" % w for w in words[i:i + 8]) + ",\n")
    f.write("};\n\n/* 4 CLUT variants x 16 colours: 0 street, 1 blue, 2 brick, 3 teal */\n")
    f.write("static const uint16_t city_clut[64] __attribute__((aligned(4))) = {\n")
    for v in cluts: f.write("\t" + ",".join("0x%04x" % c for c in v) + ",\n")
    f.write("};\n#endif\n")
print("ok", len(words) * 4, "bytes tex")
try:
    from PIL import Image
    pal = [c for c in cluts[1]]
    rgb = [((c & 31) << 3, ((c >> 5) & 31) << 3, ((c >> 10) & 31) << 3) for c in pal]
    img = Image.new("RGB", (W, H))
    img.putdata([rgb[v] for v in A.reshape(-1)])
    img.resize((W * 3, H * 3), Image.NEAREST).save(os.path.join(os.path.dirname(os.path.abspath(__file__)), "city_atlas_x3.png"))
except Exception as e:
    print("preview skipped", e)
